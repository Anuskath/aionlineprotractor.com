export function useTranslations(lang: string = DEFAULT_LANGUAGE): UIStrings {
  return UI_TRANSLATIONS[lang] || UI_TRANSLATIONS[DEFAULT_LANGUAGE];
}

export function getLocalizedPath(path: string, lang: string = DEFAULT_LANGUAGE): string {
  const cleanPath = path.startsWith('/') ? path : `/${path}`;
  if (lang === DEFAULT_LANGUAGE) {
    return cleanPath;
  }
  return `/${lang}${cleanPath === '/' ? '' : cleanPath}`;
}
